export type SocialName = keyof typeof paths;

/** Redes con ícono propio a color (3D). */
export const COLOR_ICONS: ReadonlySet<SocialName> = new Set<SocialName>(["facebook", "whatsapp"]);

export function SocialIcon({ name, className = "size-5" }: { name: keyof typeof paths; className?: string }) {
  if (name === "facebook") return <Facebook3D className={className} />;
  if (name === "whatsapp") return <WhatsApp3D className={className} />;
  return (
    <svg viewBox="0 0 24 24" className={className} fill="currentColor" aria-hidden>
      <path d={paths[name]} />
    </svg>
  );
}

export function socialLinks(s: PublicSettings) {
  const list: Array<{ name: keyof typeof paths; label: string; url: string }> = [];
  if (s.instagramUrl) list.push({ name: "instagram", label: "Instagram", url: s.instagramUrl });
  if (s.facebookUrl) list.push({ name: "facebook", label: "Facebook", url: s.facebookUrl });
  if (s.tiktokUrl) list.push({ name: "tiktok", label: "TikTok", url: s.tiktokUrl });
  if (s.xUrl) list.push({ name: "x", label: "X", url: s.xUrl });
  if (s.youtubeUrl) list.push({ name: "youtube", label: "YouTube", url: s.youtubeUrl });
  if (s.whatsapp) list.push({ name: "whatsapp", label: "WhatsApp", url: whatsappLink(s.whatsapp) });
  return list;
}
